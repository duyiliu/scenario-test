import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";
import postcss from "postcss";
import tailwindcss from "tailwindcss";
import { createDistLifecycle } from "./build-dist.mjs";

const root = path.resolve(import.meta.dirname, "..");
// 构建进 staging 目录，全部成功后 rename 交换 dist：
// 并发场景（dev 监听重建 + npm run check 同时构建）下读者要么看到完整的旧产物、
// 要么看到完整的新产物，不会读到写了一半的文件（此前 esbuild 直写 dist，
// 半成品被 init/doctor 拷走导致测试偶发失败）。目录发布与孤儿清理集中在
// build-dist.mjs（可注入 fs/sleep/pid 判断，便于故障注入单测）。
const lifecycle = createDistLifecycle({ root });
const staging = lifecycle.paths.staging;
lifecycle.cleanupOrphans();

function atomicWriteFileSync(file, content) {
    const tmp = `${file}.tmp-${process.pid}`;
    fs.writeFileSync(tmp, content, "utf8");
    // Windows 上 Node 的 rename 覆盖已存在文件（MoveFileEx + REPLACE_EXISTING）
    fs.renameSync(tmp, file);
}

const packageInfo = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
atomicWriteFileSync(
    path.join(root, "src/version.generated.js"),
    `// Generated by scripts/build.mjs from package.json.\nexport const VERSION = ${JSON.stringify(packageInfo.version)};\n`
);
fs.rmSync(staging, { recursive: true, force: true });
fs.mkdirSync(staging, { recursive: true });

// 版本写入后动态导入 contract（获得最新 VERSION），生成对外能力清单与 d.ts
const { contract } = await import(pathToFileURL(path.join(root, "src/contract.js")).href);
const { buildCapabilities } = await import(pathToFileURL(path.join(root, "src/capabilities.js")).href);
const capabilities = buildCapabilities(contract);
const capabilitiesJson = `${JSON.stringify(capabilities, null, 2)}\n`;
fs.writeFileSync(path.join(staging, "scenario-test-capabilities.json"), capabilitiesJson, "utf8");

process.argv.push("--out", staging);
await import(pathToFileURL(path.join(root, "scripts/generate-dts.mjs")).href);

const tailwindResult = await postcss([
    tailwindcss({
        content: [
            path.join(root, "src/browser/ui/ui-view.js"),
            path.join(root, "src/browser/ui/ui-adhoc.js"),
            path.join(root, "src/browser/ui/runtime.js")
        ],
        important: "#scenario-test-root",
        theme: { extend: {} },
        plugins: []
    })
]).process("@tailwind base; @tailwind components; @tailwind utilities;", { from: undefined });
atomicWriteFileSync(
    path.join(root, "src/browser/tailwind.generated.js"),
    `// Generated by scripts/build.mjs.\nexport const TAILWIND_CSS = ${JSON.stringify(tailwindResult.css)};\n`
);

const shared = {
    bundle: true,
    sourcemap: true,
    legalComments: "inline",
    logLevel: "info",
    banner: { js: `/*! scenario-test v${packageInfo.version} */` }
};

await build({
    ...shared,
    entryPoints: [path.join(root, "src/index.js")],
    outfile: path.join(staging, "scenario-test.umd.js"),
    platform: "browser",
    format: "iife",
    globalName: "ScenarioTest",
    target: ["chrome100"]
});

await build({
    ...shared,
    entryPoints: [path.join(root, "src/index.js")],
    outfile: path.join(staging, "scenario-test.esm.js"),
    platform: "browser",
    format: "esm",
    target: ["es2020"]
});

await build({
    ...shared,
    entryPoints: [path.join(root, "src/node.js")],
    outfile: path.join(staging, "scenario-test.cjs"),
    platform: "node",
    format: "cjs",
    target: ["node18"]
});

await build({
    ...shared,
    entryPoints: [path.join(root, "src/cli.js")],
    outfile: path.join(staging, "scenario-test-cli.cjs"),
    platform: "node",
    format: "cjs",
    target: ["node18"],
    // CLI 产物作为 npm bin：需要 shebang 才能被 npx/命令行直接执行
    banner: { js: `#!/usr/bin/env node\n/*! scenario-test v${packageInfo.version} */` }
});

// 构建全部成功后才替换 dist：具体发布协议（备份、250ms 重试、cp 回退、
// 失败回滚）集中在 build-dist.mjs，便于用故障注入做确定性单测。
await lifecycle.publish();
