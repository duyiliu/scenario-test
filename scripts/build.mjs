import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";
import postcss from "postcss";
import tailwindcss from "tailwindcss";

const root = path.resolve(import.meta.dirname, "..");
const dist = path.join(root, "dist");
// 构建进 staging 目录，全部成功后 rename 交换 dist：
// 并发场景（dev 监听重建 + npm run check 同时构建）下读者要么看到完整的旧产物、
// 要么看到完整的新产物，不会读到写了一半的文件（此前 esbuild 直写 dist，
// 半成品被 init/doctor 拷走导致测试偶发失败）。
const staging = path.join(root, `dist.staging-${process.pid}`);

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

// 并发安全不靠互斥锁而靠协议：dist 位置只会被原子 rename 换入完整产物，
// 本进程失败路径绝不向 dist 写入半成品——因此回滚时 dist 存在即视为
// 他人产物（不得删），启动还原仅在无活跃构建（无存活 staging pid）时进行
function hasLiveStagingBuild() {
    for (const name of fs.readdirSync(root)) {
        const match = /^dist\.staging-(\d+)$/.exec(name);
        if (!match) continue;
        try {
            process.kill(Number(match[1]), 0);
            return true;
        } catch (error) {
            if (error?.code !== "ESRCH") return true;
        }
    }
    return false;
}

// 清理上次构建中断遗留的 staging/swap/backup/trash/restore 目录：目录名带构建
// 进程 pid，仅当该 pid 已不存活才处理（pid 复用时宁可不动），避免误伤并发构建。
// backup/restore 是「可能唯一完整的旧产物」：删除与还原都必须先经原子 rename
// 认领进本进程独占命名空间——直接 rmSync 递归删除中途失败会留下残缺目录，
// 残缺源被自动还原为 dist 会产生丢产物的成品；trash-* 只删不还原，
// restore-* 是认领成功后的完整副本，按 backup 同口径处理
const claimed = path.join(root, `dist.restore-${process.pid}`);
const trash = path.join(root, `dist.trash-${process.pid}`);
for (const name of fs.readdirSync(root)) {
    const match = /^dist\.(staging|swap|backup|restore|trash)-(\d+)$/.exec(name);
    if (!match) continue;
    try {
        process.kill(Number(match[2]), 0);
    } catch (error) {
        // 仅 ESRCH（No such process）能证明 pid 已死亡；EPERM 是「存在但无权限」
        // （跨权限上下文的活跃构建），其余错误同样保守跳过——宁可不删不误伤
        if (error?.code !== "ESRCH") continue;
        const orphan = path.join(root, name);
        const kind = match[1];
        if (kind === "backup" || kind === "restore") {
            // 认领：rename 是原子操作，成功即独占源目录（另一进程同时认领会失败跳过）
            try { fs.renameSync(orphan, claimed); } catch { continue; }
            if (fs.existsSync(dist)) {
                // dist 已就位：认领到的旧产物冗余——移出可恢复命名空间再删，
                // 删除中断留下的 trash-* 下轮只会继续清理、不会被还原
                try {
                    fs.renameSync(claimed, trash);
                    fs.rmSync(trash, { recursive: true, force: true });
                } catch { /* 残留 trash 无碍 */ }
            } else if (hasLiveStagingBuild()) {
                // 其他构建正处发布窗口：还原命名空间，等它落定后再处理
                try { fs.renameSync(claimed, orphan); } catch { /* 留在 restore-* 下轮再处理 */ }
            } else {
                try {
                    fs.renameSync(claimed, dist);
                } catch {
                    // 就位失败（如另一发布者抢先占位）：dist 已出现则认领内容冗余——
                    // 仍须先转 trash 命名空间再删，直接删 restore-* 会留下残缺的
                    // 可恢复源；dist 仍缺失则还原原命名空间保留恢复能力
                    try {
                        if (fs.existsSync(dist)) {
                            fs.renameSync(claimed, trash);
                            fs.rmSync(trash, { recursive: true, force: true });
                        } else {
                            fs.renameSync(claimed, orphan);
                        }
                    } catch { /* 保留完整 claimed 供下次恢复 */ }
                }
            }
        } else {
            fs.rmSync(orphan, { recursive: true, force: true });
        }
    }
}

function atomicWriteFileSync(file, content) {
    const tmp = `${file}.tmp-${process.pid}`;
    fs.writeFileSync(tmp, content, "utf8");
    // Windows 上 Node 的 rename 覆盖已存在文件（MoveFileEx + REPLACE_EXISTING）
    fs.renameSync(tmp, file);
}

