// 构建全部成功后才替换 dist。Windows 无目录原子交换，发布分两段：
//   1) 旧 dist 先 rename 为 dist.backup-<pid>（不是删除——rename 失败则全程未动，
//      比直接 rm 再 rename 少一个「dist 已删、rename 仍失败」的丢产物窗口）；
//   2) staging rename 就位（250ms 间隔重试抗瞬时锁），持续失败回退 cp 到
//      dist.swap-<pid> 再换入——直接 cp 进 dist 会让读者看到逐文件半成品。
// 任一步失败回滚：backup rename 回 dist——旧产物全程可还原，不存在 dist 缺失终态；
// backup rename 本身失败则中止抛错（旧 dist 原封未动，比旧路径强）。
const backup = path.join(root, `dist.backup-${process.pid}`);
const swap = path.join(root, `dist.swap-${process.pid}`);
const hadDist = fs.existsSync(dist);
// 清理同名残留（pid 复用留下的旧 backup/swap）：dist 缺失时同名 backup 可能是
// 唯一旧版恢复候选——此时不清它（发布失败/中断后要能还原），仅当 dist 存在
// （马上被覆盖进同名 backup）才先转 trash 命名空间再删，删除中断的残留不进还原
if (hadDist) {
    try {
        fs.renameSync(backup, trash);
        fs.rmSync(trash, { recursive: true, force: true });
    } catch { /* backup 不存在或占用：继续，后续 dist→backup rename 会明确失败 */ }
}
fs.rmSync(swap, { recursive: true, force: true });
let distMoved = false;
try {
    if (hadDist) {
        fs.renameSync(dist, backup);
        distMoved = true;
    }
    let swapped = false;
    for (let attempt = 0; attempt < 4 && !swapped; attempt += 1) {
        try {
            fs.renameSync(staging, dist);
            swapped = true;
        } catch {
            if (attempt < 3) await sleep(250);
        }
    }
    if (!swapped) {
        fs.cpSync(staging, swap, { recursive: true });
        fs.renameSync(swap, dist);
    }
} catch (error) {
    // 回滚：本进程的失败路径不可能在 dist 位置留下半成品（新产物只经原子
    // rename 就位，cp 只落到 swap）——因此 dist 存在即视为他人完整产物
    // （旧的或并发构建刚发布的），绝不删除；缺失时才还原 backup。
    // 每步清理独立容错，不得阻断还原与抛错
    try { fs.rmSync(swap, { recursive: true, force: true }); } catch { /* 残留无碍 */ }
    if (distMoved) {
        if (fs.existsSync(dist)) {
            error.message += `；dist 已被其他构建发布接管，旧产物备份保留在 ${backup} 供人工核对`;
        } else {
            try {
                fs.renameSync(backup, dist);
            } catch (restoreError) {
                // 还原失败：明示 backup 路径供手动恢复（下次构建启动清理遇到
                // dist 缺失 + 死 pid + 无活跃构建的 backup 时会自动还原）
                error.message += `；旧产物备份保留在 ${backup}（自动还原失败: ${restoreError.message}），可手动 rename 回 dist`;
            }
        }
    }
    throw error;
}
// 就位后的清理失败不影响发布结果：staging/backup 孤儿目录由下次构建按 pid 存活
// 检测清理；backup 先移入 trash 命名空间再递归删——删除中断的残留只会继续被清理，
// 不会被误当成完整备份还原
try { fs.rmSync(staging, { recursive: true, force: true }); } catch { /* 残留无碍 */ }
// backup 存在即冗余（新产物已就位，无论它是本次 distMoved 产物还是同名残留），
// 一律先转 trash 命名空间再删
try {
    if (fs.existsSync(backup)) {
        fs.renameSync(backup, trash);
        fs.rmSync(trash, { recursive: true, force: true });
    }
} catch { /* 残留无碍 */ }
